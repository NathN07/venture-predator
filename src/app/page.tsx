type Stats = {
  interrogations: number;
  verified: number;
  median_score: number;
  capital_offered_m: number;
};

async function load() {
  if (!isSupabaseConfigured) return { signedIn: false, stats: null as Stats | null };
  try {
    const supabase = await createClient();
    const [{ data: auth }, { data: stats }] = await Promise.all([
      supabase.auth.getUser(),
      supabase.rpc("platform_stats"),
    ]);
    return { signedIn: Boolean(auth.user), stats: (stats as Stats | null) ?? null };
  } catch {
    return { signedIn: false, stats: null as Stats | null };
  }
}

